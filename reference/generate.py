#!/usr/bin/env python3
"""Independent 60-digit Decimal RK4, three refinements; no production core imports.
Golden values require observed fourth-order convergence before extrapolation.
Regenerate: python3 reference/generate.py (standard library only).
"""
from decimal import Decimal as D, getcontext
from pathlib import Path
import json, hashlib
getcontext().prec=60
seeds=[('figure-eight', [['-0.97000436','.24308753','0','.466203685','.43236573','0','1'],['.97000436','-.24308753','0','.466203685','.43236573','0','1'],['0','0','0','-.93240737','-.86473146','0','1']]),('asymmetric-3d',[['-1','.2','.05','.35','.45','.08','1'],['.95','-.24','-.08','.52','.32','-.05','.85'],['.08','.08','.15','-.65','-.62','.02','1.15']]),('unequal-mass',[['-.5','0','0','0','-.4','.02','1'],['.5','0','0','0','.5','-.02','.8'],['0','2','.3','.2','0','0','.2']])]
seeds.append(('close-pair', [['-.04','0','0','0','-2.5','0','1'],['.04','0','0','0','2.5','0','1'],['0','2','.3','.05','0','0','.2']]))
def derivative(y,m):
 out=[v for b in y for v in b[3:6]] # replaced below to keep body-major layout
 out=[]
 for i in range(3):
  a=[D(0)]*3
  for j in range(3):
   if i==j: continue
   r=[y[j][k]-y[i][k] for k in range(3)];r2=sum(x*x for x in r)
   if not r2: raise RuntimeError('collision')
   scale=m[j]/(r2*r2.sqrt())
   a=[a[k]+r[k]*scale for k in range(3)]
  out.append(y[i][3:6]+a)
 return out
def solve(y,m,n,duration):
 h=duration/n;y=[b[:] for b in y];check=[]
 def add(y,k,s):return [[y[i][j]+s*k[i][j] for j in range(6)]for i in range(3)]
 for step in range(n):
  a=derivative(y,m);b=derivative(add(y,a,h/2),m);c=derivative(add(y,b,h/2),m);d=derivative(add(y,c,h),m)
  y=[[y[i][j]+h*(a[i][j]+2*b[i][j]+2*c[i][j]+d[i][j])/6 for j in range(6)]for i in range(3)]
  if step+1 in (n//2,n):check.append([v for b in y for v in b])
 return check
records=[]
for name,rows in seeds:
 rows=[[D(v)for v in r]for r in rows];m=[r[6]for r in rows];mass=sum(m)
 for axis in range(6):
  mean=sum(r[axis]*r[6]for r in rows)/mass
  for r in rows:r[axis]-=mean
 duration=D(".02") if name=="close-pair" else D(".5")
 coarse,mid,fine=[solve([r[:6]for r in rows],m,n,duration)for n in (512,1024,2048)]
 checks=[]
 for index,t in enumerate((str(duration/2),str(duration))):
  a,b,c=coarse[index],mid[index],fine[index]
  e1=max(abs(x-y)for x,y in zip(a,b));e2=max(abs(x-y)for x,y in zip(b,c));ratio=e1/e2
  assert D(10)<ratio<D(24),(name,t,ratio)
  golden=[z+(z-y)/15 for y,z in zip(b,c)]
  assert e2/15<D('1e-10')
  checks.append(dict(time=t,refinementRatio=str(ratio),estimatedCorrection=str(e2/15),state=[str(x)for x in golden]))
 records.append(dict(name=name,duration=str(duration),initial=[[str(v)for v in r]for r in rows],checkpoints=checks))
 print(name,[(c['time'],c['estimatedCorrection'])for c in checks],flush=True)
out=Path(__file__).parent
payload=dict(method='Decimal 60 digits RK4, 512/1024/2048 steps per segment duration; Richardson extrapolation; empirical error estimate, not rigorous bound',generatorSha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),segments=records)
(out/'short_windows.json').write_text(json.dumps(payload,indent=2)+'\n')
lines=['// Generated by reference/generate.py; do not hand edit.','#pragma once','namespace threebody {','struct ReferenceSegment { const char *name; double duration; double initial[3][7]; double checkpoints[2][18]; };','static const ReferenceSegment referenceSegments[] = {']
for r in records:
 lines+=['{"'+r['name']+'", '+r['duration']+', {'+','.join('{'+','.join(row)+'}'for row in r['initial'])+'}, {'+','.join('{'+','.join(c['state'])+'}'for c in r['checkpoints'])+'}},']
lines+=['};','}']
(out/'ShortWindows.h').write_text('\n'.join(lines)+'\n')
